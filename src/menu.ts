/**
 * `TE Menu`: one Tasker task (imported once with the project XML) that lists
 * every standalone task in a Scenes v2 dialog and runs the one you tap, so a
 * single gesture or shortcut reaches all of them without per-task imports.
 *
 * Flow: the imported `TE Menu` task runs `TE Dispatch` with %par1 = "TE Menu";
 * the dispatcher maps that name to {@link MENU_SCRIPT_FILENAME} and `eval`s
 * it in its own scope (so `TASKS` and `base` are visible). The script
 * publishes the task names in %TE_MENU_ITEMS, shows the menu scene and polls
 * %TE_MENU_PICK, which the WebView sets when an entry is tapped, then
 * evaluates the picked task's file in place.
 */

/** Name of the imported menu task (also its dispatcher map key) */
export const MENU_TASK_NAME = "TE Menu";

/** Synced script evaluated by the dispatcher for {@link MENU_TASK_NAME} */
export const MENU_SCRIPT_FILENAME = "te-menu.js";

/** Synced Scenes v2 layout hosting the menu WebView */
export const MENU_SCENE_FILENAME = "te-menu.scene.json";

/** Synced WebView page listing the tasks */
export const MENU_HTML_FILENAME = "te-menu.html";

/** Value of %TE_MENU_PICK while nothing has been picked */
const NO_PICK = "-";

/** How long the menu waits for a tap, in milliseconds */
export const MENU_TIMEOUT_MS = 120_000;

const POLL_MS = 250;

/**
 * Menu logic. `eval`ed inside the dispatcher, where `TASKS` (name → file),
 * `base` (device JS dir) and the Tasker JS globals are in scope.
 */
export const menuScriptJs = (showSceneTask: string, placeholder: string): string =>
  [
    "/**",
    " * TE Menu: list the standalone tasks and run the tapped one.",
    " *",
    " * Generated by tasker-effect. Do not edit by hand.",
    " * Evaluated by the dispatcher; its TASKS and base variables are in scope.",
    " */",
    "var __items = [];",
    "for (var __name in TASKS) {",
    `  if (TASKS.hasOwnProperty(__name) && __name !== ${JSON.stringify(MENU_TASK_NAME)}) __items.push(__name);`,
    "}",
    'setGlobal("TE_MENU_ITEMS", JSON.stringify(__items));',
    `setGlobal("TE_MENU_PICK", ${JSON.stringify(NO_PICK)});`,
    `var __scene = readFile(base + ${JSON.stringify(MENU_SCENE_FILENAME)});`,
    'if (__scene === undefined || __scene === "") {',
    `  flash(${JSON.stringify(`tasker-effect: could not read ${MENU_SCENE_FILENAME}`)});`,
    "} else {",
    `  performTask(${JSON.stringify(showSceneTask)}, 10, __scene.split(${JSON.stringify(placeholder)}).join(base));`,
    `  var __pick = ${JSON.stringify(NO_PICK)};`,
    `  for (var __waited = 0; __waited < ${MENU_TIMEOUT_MS} && __pick === ${JSON.stringify(NO_PICK)}; __waited += ${POLL_MS}) {`,
    `    wait(${POLL_MS});`,
    '    __pick = global("TE_MENU_PICK");',
    `    if (__pick === undefined || __pick === null || __pick === "") __pick = ${JSON.stringify(NO_PICK)};`,
    "  }",
    // Run the pick right here: performing TE Dispatch again would be
    // dropped, since TE Dispatch is still running this menu (Tasker's
    // default collision handling aborts the new instance).
    "  if (TASKS.hasOwnProperty(__pick)) {",
    "    var __source = readFile(base + TASKS[__pick]);",
    '    if (__source === undefined || __source === "") {',
    '      flash("tasker-effect: could not read " + base + TASKS[__pick]);',
    "    } else {",
    "      eval(__source);",
    "    }",
    "  }",
    "}",
    "",
  ].join("\n");

/** Scenes v2 layout for the menu; the WebView path uses the JS-dir placeholder */
export const menuSceneJson = (placeholder: string): string =>
  `${JSON.stringify(
    {
      name: MENU_TASK_NAME,
      description: "tasker-effect task menu",
      defaultDisplayMode: "Dialog",
      root: {
        type: "Column",
        id: "root",
        modifiers: [{ type: "FillWidth" }],
        children: [
          {
            type: "WebView",
            id: "menu",
            content: `${placeholder}${MENU_HTML_FILENAME}`,
            jsBridgeEnabled: true,
            backgroundColor: "#1C1B1F",
            modifiers: [{ type: "FillWidth" }, { type: "Size", height: "420" }],
          },
        ],
      },
    },
    null,
    2
  )}\n`;

/** WebView page: one button per task; tapping sets %TE_MENU_PICK and closes */
export const menuHtml = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Tasks</title>
<style>
  :root { --bg: #1c1b1f; --card: #2b2930; --text: #e6e1e5; --muted: #a8a2ad; }
  @media (prefers-color-scheme: light) {
    :root { --bg: #fffbfe; --card: #f3edf7; --text: #1c1b1f; --muted: #625b71; }
  }
  * { box-sizing: border-box; }
  html, body { margin: 0; background: var(--bg); color: var(--text);
    font: 16px/1.4 system-ui, -apple-system, Roboto, sans-serif; }
  h1 { font-size: 18px; font-weight: 600; margin: 0; padding: 16px 16px 8px; }
  ul { list-style: none; margin: 0; padding: 0 12px 12px; }
  li { background: var(--card); border-radius: 16px; margin-bottom: 8px;
    padding: 14px; cursor: pointer; }
  li:active { opacity: .7; }
  .empty { color: var(--muted); text-align: center; padding: 32px 16px; }
</style>
</head>
<body>
<h1>Tasks</h1>
<ul id="list"></ul>
<p class="empty" id="empty" hidden>No tasks.</p>
<script>
  // Runs inside a Tasker Scenes v2 WebView with the JS bridge enabled.
  var bridge = window.Tasker;
  var items = [];
  try {
    items = bridge ? JSON.parse(bridge.getVariable("TE_MENU_ITEMS") || "[]") : ["Sample task"];
  } catch (err) {
    items = [];
  }
  var list = document.getElementById("list");
  document.getElementById("empty").hidden = items.length > 0;
  items.forEach(function (name) {
    var item = document.createElement("li");
    item.textContent = name;
    item.addEventListener("click", function () {
      if (!bridge) return;
      bridge.setVariable("TE_MENU_PICK", name);
      bridge.dismissLayout(bridge.getCurrentScreenId());
    });
    list.appendChild(item);
  });
</script>
</body>
</html>
`;
